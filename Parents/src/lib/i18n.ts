export type Key = keyof typeof sw;
const DICT: Record<Lang, typeof sw> = { sw, en };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s: string = DICT[lang][key] ?? sw[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

const MONTHS: Record<Lang, string[]> = {
  sw: ['Jan', 'Feb', 'Mac', 'Apr', 'Mei', 'Jun', 'Jul', 'Ago', 'Sep', 'Okt', 'Nov', 'Des'],
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
};
// 18 Nov 2026 (same shape in both languages, only the month name changes)
export function fmtDate(lang: Lang, d?: string | null, withTime = false) {
  if (!d) return '';
  const x = new Date(d);
  const s = `${x.getDate()} ${MONTHS[lang][x.getMonth()]} ${x.getFullYear()}`;
  return withTime ? `${s}, ${String(x.getHours()).padStart(2, '0')}:${String(x.getMinutes()).padStart(2, '0')}` : s;
}
// 1745000 -> "1,745,000"
export const tsh = (n: number) => String(Math.round(Number(n) || 0)).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
