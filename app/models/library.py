"""Library models: book titles and physical copies.

A :class:`BookTitle` is the intellectual work held in the catalogue; a
:class:`BookCopy` is one physical copy with a unique, readable code held at a
branch. Copy codes are generated by :mod:`app.utils.codes`.
"""

from __future__ import annotations

import enum
from datetime import datetime, timezone
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, Enum, ForeignKey, Integer, String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.branch import Branch
    from app.models.request import Request


class BookCopyStatus(str, enum.Enum):
    """Availability state of a physical book copy."""

    AVAILABLE = "AVAILABLE"
    ISSUED = "ISSUED"
    LOST = "LOST"
    WRITTEN_OFF = "WRITTEN_OFF"


def _utcnow() -> datetime:
    """Return the current UTC time (portable across databases)."""
    return datetime.now(timezone.utc)


class BookTitle(Base):
    """A book title held in the library catalogue."""

    __tablename__ = "book_titles"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    title: Mapped[str] = mapped_column(String(255), index=True, nullable=False)
    author: Mapped[str | None] = mapped_column(String(160), nullable=True)
    isbn: Mapped[str | None] = mapped_column(String(40), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime, default=_utcnow, nullable=False
    )

    copies: Mapped[list["BookCopy"]] = relationship(back_populates="title")


class BookCopy(Base):
    """One physical copy of a book title, stored at a single branch."""

    __tablename__ = "book_copies"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    code: Mapped[str] = mapped_column(
        String(40), unique=True, index=True, nullable=False
    )
    title_id: Mapped[int] = mapped_column(
        ForeignKey("book_titles.id"), nullable=False, index=True
    )
    branch_id: Mapped[int] = mapped_column(
        ForeignKey("branches.id"), nullable=False, index=True
    )
    status: Mapped[BookCopyStatus] = mapped_column(
        Enum(BookCopyStatus, native_enum=False, length=16),
        nullable=False,
        default=BookCopyStatus.AVAILABLE,
    )
    request_id: Mapped[int | None] = mapped_column(
        ForeignKey("requests.id", ondelete="SET NULL"), nullable=True, index=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime, default=_utcnow, nullable=False
    )

    title: Mapped["BookTitle"] = relationship(back_populates="copies")
    branch: Mapped["Branch"] = relationship()
    request: Mapped["Request | None"] = relationship()
